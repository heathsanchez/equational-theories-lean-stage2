#!/usr/bin/env python3
import importlib.util, json, subprocess, sys, tempfile, time
from itertools import product
from pathlib import Path
from datasets import load_dataset

ROOT = Path(__file__).resolve().parents[2]
PROTO = ROOT / 'experiments/mathgraph/protocols/methodology-0036-reentry-gate-v1.json'
OUT = ROOT / 'experiments/mathgraph/results/methodology-0036-reentry-gate.json'
RID = 'evaluation_normal_0036'
HIST = 'origin/mathgraph/superposition-selector-tournament-20260820'


def load_historical():
    text = subprocess.check_output(['git', 'show', f'{HIST}:submissions/mathgraph/solver.py'], text=True)
    p = Path(tempfile.gettempdir()) / 'mathgraph_methodology_0036_reentry_hist.py'
    p.write_text(text)
    spec = importlib.util.spec_from_file_location('mg_methodology_0036_reentry_hist', p)
    m = importlib.util.module_from_spec(spec)
    sys.modules[spec.name] = m
    spec.loader.exec_module(m)
    return m


def connected(search, target):
    comps = search.components()
    a, b = target[:2]
    return a in comps and b in comps and comps[a] == comps[b]


def main():
    protocol = json.loads(PROTO.read_text())
    assert protocol['frozen_before_execution'] is True
    assert protocol['id'] == RID
    assert RID not in protocol['constraints']['sealed_transfer_ids']
    m = load_historical()
    row = next(dict(r) for r in load_dataset('SAIRfoundation/equational-theories-selected-problems', 'evaluation_normal', split='train') if r['id'] == RID)
    source = m.parse_equation(row['equation1'])
    target = m.parse_equation(row['equation2'])

    captured = []
    Base = m.ContextualSearch
    class Instrumented(Base):
        def add_node(self, node, graph_edge=True):
            nid = super().add_node(node, graph_edge=graph_edge)
            if nid is not None and getattr(node, 'constructor', None) == 'target-narrowing':
                captured.append(node)
            return nid

    cfg = m.CONTEXTUAL_PORTFOLIO[0]
    search = Instrumented(source, target, time.monotonic() + 8.0, dict(cfg['limits']))
    parent_found = search.solve_target_narrowing(cfg['maximum_depth'], cfg['branching'], cfg['maximum_terms'], cfg['maximum_context_depth'])
    parent_edges = search.graph_edges
    parent_connected = connected(search, target)

    tl, tr = target[:2]
    exact = []
    seen = set()
    for node in captured:
        for side_name, term in (('lhs', node.lhs), ('rhs', node.rhs)):
            if term == tl or term == tr:
                key = repr(term)
                if key not in seen:
                    seen.add(key)
                    exact.append({'which': 'target_lhs' if term == tl else 'target_rhs', 'side': side_name, 'term': term})

    if not any(e['which'] == 'target_rhs' for e in exact):
        decision = 'R4_MEASUREMENT_ARTIFACT'
        added = 0
        post_connected = parent_connected
        replay = False
        root = None
        reentry_attempts = 0
    else:
        # Use only literal target endpoints generated by the frozen parent search.
        reentry_terms = []
        for e in exact:
            if e['term'] not in reentry_terms:
                reentry_terms.append(e['term'])
        target_vars = [("var", v) for v in target[2]]
        source_vars = list(source[2])
        before = search.graph_edges
        reentry_attempts = 0
        for term in reentry_terms:
            for pos in range(len(source_vars)):
                other_positions = [i for i in range(len(source_vars)) if i != pos]
                for fillers in product(target_vars, repeat=len(other_positions)):
                    values = [None] * len(source_vars)
                    values[pos] = term
                    for i, filler in zip(other_positions, fillers):
                        values[i] = filler
                    search.add_source_substitution(values, generation=1, origins=())
                    reentry_attempts += 1
        added = search.graph_edges - before
        post_connected = connected(search, target)
        path = search.shortest_path()
        replay = bool(path is not None and m.replay_dag(source, path[0], path[1]))
        root = path[1] if path is not None else None
        if replay or post_connected:
            decision = 'R1_REENTRY_FAILURE'
        elif added > 0:
            decision = 'R3_DEEPER_SEARCH_REQUIRED'
        else:
            decision = 'R2_CHAIN_ASSEMBLY_FAILURE'

    out = {
        'schema': 'mathgraph.methodology-0036-reentry-gate.v1',
        'id': RID,
        'protocol_precommitted': True,
        'equations': {'source': row['equation1'], 'target': row['equation2']},
        'parent': {
            'closure': bool(parent_found is not None),
            'graph_edges': parent_edges,
            'connected': parent_connected,
            'captured_target_narrowing_nodes': len(captured)
        },
        'exact_target_endpoint_audit': {
            'count': len(exact),
            'which': [e['which'] for e in exact],
            'rendered': [m.render_term(e['term']) for e in exact]
        },
        'reentry': {
            'attempts': reentry_attempts,
            'new_graph_edges': added,
            'post_connected': post_connected,
            'replayable_closure': replay,
            'root': root
        },
        'decision': decision,
        'sealed_transfer_ids_loaded': []
    }
    OUT.parent.mkdir(parents=True, exist_ok=True)
    OUT.write_text(json.dumps(out, indent=2, sort_keys=True) + '\n')
    print(json.dumps(out, indent=2, sort_keys=True), flush=True)

if __name__ == '__main__':
    main()
